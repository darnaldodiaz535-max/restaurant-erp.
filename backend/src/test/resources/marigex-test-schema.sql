CREATE TABLE APP_NOTIF_PREFERENCIA (ID_USUARIO NUMBER PRIMARY KEY,
INTERNA CHAR(1) DEFAULT 'S' NOT NULL, PUSH CHAR(1) DEFAULT 'N' NOT NULL,
CORREO CHAR(1) DEFAULT 'N' NOT NULL, EMAIL VARCHAR2(254 CHAR),
CONSTRAINT FK_PREF_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES APP_USUARIO(ID_USUARIO) ON DELETE CASCADE,
CONSTRAINT CK_PREF_INTERNA CHECK(INTERNA IN ('S','N')),
CONSTRAINT CK_PREF_PUSH CHECK(PUSH IN ('S','N')),
CONSTRAINT CK_PREF_CORREO CHECK(CORREO IN ('S','N')));
CREATE TABLE APP_PUSH_SUSCRIPCION (ID_SUSCRIPCION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
ID_USUARIO NUMBER NOT NULL, ENDPOINT VARCHAR2(2000 CHAR) NOT NULL,
ENDPOINT_HASH VARCHAR2(64 CHAR) NOT NULL UNIQUE,
P256DH VARCHAR2(100 CHAR) NOT NULL, AUTH VARCHAR2(40 CHAR) NOT NULL,
ACTUALIZADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
CONSTRAINT FK_PUSH_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES APP_USUARIO(ID_USUARIO) ON DELETE CASCADE);
CREATE TABLE APP_NOTIF_ENVIO (ID_ENVIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
ID_NOTIFICACION NUMBER NOT NULL, CANAL VARCHAR2(10 CHAR) NOT NULL,
DESTINO VARCHAR2(254 CHAR) NOT NULL,
ESTADO VARCHAR2(12 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
INTENTOS NUMBER DEFAULT 0 NOT NULL,
PROXIMO_INTENTO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
ULTIMO_ERROR VARCHAR2(100 CHAR),
CONSTRAINT FK_ENVIO_NOTIF FOREIGN KEY(ID_NOTIFICACION) REFERENCES APP_NOTIFICACION(ID_NOTIFICACION) ON DELETE CASCADE,
CONSTRAINT UQ_ENVIO_DEST UNIQUE(ID_NOTIFICACION,CANAL,DESTINO),
CONSTRAINT CK_ENVIO_CANAL CHECK(CANAL IN ('PUSH','EMAIL')),
CONSTRAINT CK_ENVIO_ESTADO CHECK(ESTADO IN ('PENDIENTE','ENVIANDO','ENVIADO','OMITIDO','FALLIDO')));
