    @Test void completeDeletionRemovesPersonalHistoryAndAccessButPreservesOtherEmployees() throws Exception {
        mvc.perform(delete("/api/empleados/2").session(session(101))).andExpect(status().isNoContent());
        assertEquals(2,count("APP_EMPLEADO")); assertEquals(2,count("APP_USUARIO"));
        for (String table:java.util.List.of("APP_ASISTENCIA","APP_TURNO","APP_TAREA_DIARIA","APP_EVIDENCIA_TAREA","APP_NOTIFICACION","APP_NOTIF_ENVIO","APP_PUSH_SUSCRIPCION","APP_CHECKIN_DIA","APP_CHECKIN_TAREA","APP_CHECKIN_FOTO","APP_ASISTENCIA_HORARIO","APP_COMUNICACION","APP_FERIADO_USO")) assertEquals(1,count(table),table);
        assertEquals(0,count("APP_EVAL_JEFATURA"));
        assertEquals(1,count("APP_ASISTENCIA_PLANILLA"));
        assertNull(jdbc.queryForObject("SELECT CREADO_POR FROM APP_ASISTENCIA_PLANILLA",Long.class));
        assertNull(jdbc.queryForObject("SELECT REGISTRADO_POR FROM APP_FERIADO_USO",Long.class));
        assertEquals(2,count("APP_CHECKIN_REGISTRO")); // Area templates/assignments are shared.
        assertEquals("PENDIENTE",jdbc.queryForObject("SELECT ESTADO FROM APP_CHECKIN_REGISTRO WHERE ID_REGISTRO=1",String.class));
        assertNull(jdbc.queryForObject("SELECT ID_RESPONSABLE FROM APP_CHECKIN_REGISTRO WHERE ID_REGISTRO=1",Long.class));
        assertEquals(1,count("APP_CHECKIN_EVIDENCIA"));
        assertEquals(1,jdbc.queryForObject("SELECT COMPLETADAS FROM APP_CHECKIN_RESUMEN",Integer.class));
        assertEquals(1,jdbc.queryForObject("SELECT PENDIENTES FROM APP_CHECKIN_RESUMEN",Integer.class));
        assertEquals(1,count("APP_ACTIVIDAD"));
        mvc.perform(get("/api/empleados").session(session(102))).andExpect(status().isUnauthorized());
    }

    @Test void aNewUnknownRestrictionRollsBackEveryDeletion() throws Exception {
        jdbc.execute("CREATE TABLE APP_EXTENSION_PRUEBA(ID NUMBER PRIMARY KEY,PERSONA NUMBER REFERENCES APP_EMPLEADO(ID_EMPLEADO))");
        jdbc.update("INSERT INTO APP_EXTENSION_PRUEBA VALUES(1,2)");
        mvc.perform(delete("/api/empleados/2").session(session(101))).andExpect(status().isConflict());
        assertEquals(3,count("APP_EMPLEADO")); assertEquals(3,count("APP_USUARIO"));
        assertEquals(2,count("APP_EVIDENCIA_TAREA")); assertEquals(2,count("APP_CHECKIN_EVIDENCIA"));
        assertEquals("REALIZADA",jdbc.queryForObject("SELECT ESTADO FROM APP_CHECKIN_REGISTRO WHERE ID_REGISTRO=1",String.class));
        assertEquals(2,jdbc.queryForObject("SELECT COMPLETADAS FROM APP_CHECKIN_RESUMEN",Integer.class));
        assertEquals(0,count("APP_ACTIVIDAD"));
    }

    @Test void missingSharedAuthorMigrationRejectsBeforeRemovingData() throws Exception {
        jdbc.execute("ALTER TABLE APP_ASISTENCIA_PLANILLA ALTER COLUMN CREADO_POR SET NOT NULL");
        mvc.perform(delete("/api/empleados/2").session(session(101))).andExpect(status().isConflict())
                .andExpect(jsonPath("$.error").value(org.hamcrest.Matchers.containsString("24_eliminacion_personal.sql")));
        assertEquals(3,count("APP_EMPLEADO")); assertEquals(2,count("APP_ASISTENCIA"));
    }

    @Test void deletionRequiresPermissionProtectsCurrentAccountAndHandlesMissingEmployee() throws Exception {
        mvc.perform(delete("/api/empleados/2")).andExpect(status().isUnauthorized());
        mvc.perform(delete("/api/empleados/2").session(session(103))).andExpect(status().isForbidden());
        mvc.perform(delete("/api/empleados/1").session(session(101))).andExpect(status().isConflict());
        mvc.perform(delete("/api/empleados/999").session(session(101))).andExpect(status().isNotFound());
        assertEquals(3,count("APP_EMPLEADO"));
    }

    @Test void employeeWithoutAnAccountCanAlsoBeDeletedWithTheirAssignments() throws Exception {
        jdbc.update("INSERT INTO APP_EMPLEADO VALUES(4,'Sin acceso')");
        jdbc.update("INSERT INTO APP_TAREA_DIARIA VALUES(4,4)");
        jdbc.update("INSERT INTO APP_ASISTENCIA VALUES(4,4)");
        mvc.perform(delete("/api/empleados/4").session(session(101))).andExpect(status().isNoContent());
        assertEquals(3,count("APP_EMPLEADO")); assertEquals(3,count("APP_USUARIO"));
        assertEquals(2,count("APP_TAREA_DIARIA")); assertEquals(2,count("APP_ASISTENCIA"));
    }
