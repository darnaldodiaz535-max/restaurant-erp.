        assertEquals("Persona 3",jdbc.queryForObject("SELECT RESPONSABLE FROM APP_CHECKIN_REGISTRO WHERE ID_REGISTRO=?",String.class,id));
        mvc.perform(post("/api/checkin/gestion/tareas/"+id+"/hecha").session(session(3))).andExpect(status().isConflict());
        mvc.perform(post("/api/checkin/tareas/"+id+"/hecha").session(session(2))).andExpect(status().isForbidden());
        mvc.perform(put("/api/checkin/me/libre").session(session(2))).andExpect(status().isForbidden());
        mvc.perform(put("/api/checkin/me/trabajando").session(session(3))).andExpect(status().isForbidden());
