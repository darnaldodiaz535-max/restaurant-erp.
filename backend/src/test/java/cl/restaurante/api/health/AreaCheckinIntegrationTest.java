    @Test void closedReportsBackfillPersistAndEnforceOwnArea() throws Exception {
        LocalDate week=today.with(TemporalAdjusters.previousOrSame(DayOfWeek.MONDAY)).minusWeeks(1);
        jdbc.update("UPDATE APP_CHECKIN_CONFIG SET INICIO=?",Date.valueOf(week));
        template(1,"COCINA","SIMPLE",week); service.reconcile(); service.reconcile();
        assertEquals(4,jdbc.queryForObject("SELECT COUNT(*) FROM APP_CHECKIN_RESUMEN",Integer.class));
        assertEquals(4,jdbc.queryForObject("SELECT COUNT(*) FROM APP_NOTIFICACION WHERE ID_USUARIO=1",Integer.class)); // four area reports
        mvc.perform(get("/api/checkin/gestion/semanal").param("semana",week.toString()).session(session(2))).andExpect(status().isForbidden());
        mvc.perform(get("/api/checkin/gestion/semanal").param("area","SALON").param("semana",week.toString()).session(session(3))).andExpect(status().isForbidden());
        mvc.perform(get("/api/checkin/gestion/semanal").param("area","COCINA").param("semana",week.toString()).session(session(3)))
                .andExpect(status().isOk()).andExpect(jsonPath("$[0].total").value(7)).andExpect(jsonPath("$[0].pending").value(7)).andExpect(jsonPath("$[0].zeroCompletion").value(true));
        mvc.perform(get("/api/checkin/gestion/semanas").param("area","COCINA").session(session(3))).andExpect(jsonPath("$[0]").value(week.toString()));
        mvc.perform(post("/api/checkin/gestion/tareas/"+task(1,week)+"/hecha").session(session(3))).andExpect(status().isConflict());
        // A subsequently inserted backdated template cannot change a finalized week's denominator.
        template(2,"COCINA","SIMPLE",week); service.reconcile();
        assertEquals(7,jdbc.queryForObject("SELECT COUNT(*) FROM APP_CHECKIN_REGISTRO WHERE FECHA>=? AND FECHA<?",Integer.class,Date.valueOf(week),Date.valueOf(week.plusWeeks(1))));
        mvc.perform(get("/api/checkin/gestion/semanal").param("semana",week.plusDays(1).toString()).session(session(1))).andExpect(status().isBadRequest());
    }

