-- Amplía los horarios de asistencia para ciclos semanales, de dos semanas,
-- ciclos rotativos y calendarios por fecha. Ejecutar una sola vez en Oracle.
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
    n NUMBER;
    old_type_column NUMBER;
BEGIN
    SELECT COUNT(*) INTO old_type_column FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA_PLANILLA' AND COLUMN_NAME='TIPO_CICLO';
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA_PLANILLA' AND COLUMN_NAME='TIPO_CICLO';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_PLANILLA ADD (TIPO_CICLO VARCHAR2(24 CHAR) DEFAULT ''ROTACION_2_SEMANAS'' NOT NULL)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA_PLANILLA' AND COLUMN_NAME='CICLO_DIAS';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_PLANILLA ADD (CICLO_DIAS NUMBER(3) DEFAULT 14 NOT NULL)'; END IF;

    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='APP_ASISTENCIA_HORARIO' AND CONSTRAINT_NAME='CK_ASIS_HOR_SEM';
    IF n>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_HORARIO DROP CONSTRAINT CK_ASIS_HOR_SEM'; END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='APP_ASISTENCIA_HORARIO' AND CONSTRAINT_NAME='CK_ASIS_HOR_DIA';
    IF n>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_HORARIO DROP CONSTRAINT CK_ASIS_HOR_DIA'; END IF;

    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA_HORARIO' AND COLUMN_NAME='SEMANA_CICLO';
    IF n>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_HORARIO MODIFY (SEMANA_CICLO NUMBER(3))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA_HORARIO' AND COLUMN_NAME='DIA_SEMANA';
    IF n>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_HORARIO MODIFY (DIA_SEMANA NUMBER(3))'; END IF;

    -- Migra las filas del ciclo antiguo: semana/día pasa a índice del día del ciclo.
    IF old_type_column=0 THEN
        UPDATE APP_ASISTENCIA_HORARIO SET SEMANA_CICLO=(SEMANA_CICLO-1)*7+DIA_SEMANA, DIA_SEMANA=1
          WHERE SEMANA_CICLO IN (1,2) AND DIA_SEMANA BETWEEN 1 AND 7;
    END IF;
    EXECUTE IMMEDIATE 'UPDATE APP_ASISTENCIA_PLANILLA SET TIPO_CICLO=''ROTACION_2_SEMANAS'', CICLO_DIAS=14 WHERE TIPO_CICLO IS NULL OR CICLO_DIAS IS NULL';
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='APP_ASISTENCIA_HORARIO' AND CONSTRAINT_NAME='CK_ASIS_HOR_SEM';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_HORARIO ADD CONSTRAINT CK_ASIS_HOR_SEM CHECK (SEMANA_CICLO BETWEEN 1 AND 62)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='APP_ASISTENCIA_HORARIO' AND CONSTRAINT_NAME='CK_ASIS_HOR_DIA';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_HORARIO ADD CONSTRAINT CK_ASIS_HOR_DIA CHECK (DIA_SEMANA=1)'; END IF;
END;
/
