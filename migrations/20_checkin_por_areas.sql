-- Ejecutar después de 08_checkin_diario.sql y 17_roles_jefatura_barra_coperia.sql.
-- Aditiva/reanudable. No borra tareas, fotos ni registros personales anteriores.
-- No carga tareas ni cambia roles de usuarios. Revisar primero en una copia de Oracle.
DECLARE
  n NUMBER;
  PROCEDURE ensure_table(t VARCHAR2, ddl VARCHAR2) IS
    found NUMBER;
  BEGIN
    SELECT COUNT(*) INTO found FROM USER_TABLES WHERE TABLE_NAME=t;
    IF found=0 THEN EXECUTE IMMEDIATE ddl; END IF;
  END;
BEGIN
  ensure_table('APP_CHECKIN_CONFIG',q'~CREATE TABLE APP_CHECKIN_CONFIG (
    ID NUMBER PRIMARY KEY, INICIO DATE NOT NULL, CONSTRAINT CK_CHECKIN_CONFIG CHECK(ID=1))~');
  -- Dynamic SQL: the table may not exist when Oracle compiles this block.
  EXECUTE IMMEDIATE q'~MERGE INTO APP_CHECKIN_CONFIG C USING (SELECT 1 ID FROM DUAL) S ON(C.ID=S.ID)
    WHEN NOT MATCHED THEN INSERT(ID,INICIO) VALUES(1,TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'America/Santiago' AS DATE)))~';

  -- Ampliar las áreas válidas preservando COPERIA para registros y módulos previos.
  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='CK_CHECKIN_PL_AREA_V2';
  IF n=0 THEN
    EXECUTE IMMEDIATE q'~ALTER TABLE APP_CHECKIN_PLANTILLA ADD CONSTRAINT CK_CHECKIN_PL_AREA_V2 CHECK(AREA IN ('COCINA','SALON','BARRA','COOPERATIVA','COPERIA')) ENABLE VALIDATE~';
  END IF;
  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='CK_CHECKIN_PL_AREA';
  IF n>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_CHECKIN_PLANTILLA DROP CONSTRAINT CK_CHECKIN_PL_AREA'; END IF;

  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='CK_APP_USUARIO_ROL_V4';
  IF n=0 THEN
    EXECUTE IMMEDIATE q'~ALTER TABLE APP_USUARIO ADD CONSTRAINT CK_APP_USUARIO_ROL_V4 CHECK(ROL IN ('ADMIN','EMPRESA','JEFE_SALON','JEFE_COCINA','JEFE_BARRA','JEFE_COPERIA','JEFE_COOPERATIVA','JEFE_LOCAL','TRABAJADOR','EMPLEADO')) ENABLE VALIDATE~';
  END IF;
  FOR c IN (SELECT CONSTRAINT_NAME FROM USER_CONSTRAINTS WHERE TABLE_NAME='APP_USUARIO'
      AND CONSTRAINT_NAME IN ('CK_APP_USUARIO_ROL','CK_APP_USUARIO_ROL_V2','CK_APP_USUARIO_ROL_V3')) LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE APP_USUARIO DROP CONSTRAINT '||c.CONSTRAINT_NAME;
  END LOOP;

  ensure_table('APP_CHECKIN_REGISTRO',q'~CREATE TABLE APP_CHECKIN_REGISTRO (
    ID_REGISTRO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PLANTILLA NUMBER NOT NULL, FECHA DATE NOT NULL, AREA VARCHAR2(12 CHAR) NOT NULL,
    TAREA VARCHAR2(250 CHAR) NOT NULL, METODO VARCHAR2(10 CHAR) NOT NULL,
    ESTADO VARCHAR2(12 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    ID_RESPONSABLE NUMBER, RESPONSABLE VARCHAR2(160 CHAR), REALIZADA_EN TIMESTAMP(6),
    CONSTRAINT UQ_CHECKIN_REG_FECHA UNIQUE(ID_PLANTILLA,FECHA),
    CONSTRAINT CK_CHECKIN_REG_AREA CHECK(AREA IN ('COCINA','SALON','BARRA','COOPERATIVA')),
    CONSTRAINT CK_CHECKIN_REG_MET CHECK(METODO IN ('SIMPLE','FOTO')),
    CONSTRAINT CK_CHECKIN_REG_EST CHECK(ESTADO IN ('PENDIENTE','REALIZADA')),
    CONSTRAINT CK_CHECKIN_REG_AUTOR CHECK(ESTADO='PENDIENTE' OR
      (ID_RESPONSABLE IS NOT NULL AND RESPONSABLE IS NOT NULL AND REALIZADA_EN IS NOT NULL)))~');
  ensure_table('APP_CHECKIN_EVIDENCIA',q'~CREATE TABLE APP_CHECKIN_EVIDENCIA (
    ID_FOTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_REGISTRO NUMBER NOT NULL UNIQUE REFERENCES APP_CHECKIN_REGISTRO(ID_REGISTRO),
    NOMBRE_ARCHIVO VARCHAR2(255 CHAR) NOT NULL, TIPO_CONTENIDO VARCHAR2(100 CHAR) NOT NULL,
    FOTO BLOB NOT NULL, CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_CHECKIN_EV_TIPO CHECK(TIPO_CONTENIDO IN ('image/jpeg','image/png','image/webp')))~');
  ensure_table('APP_CHECKIN_RESUMEN',q'~CREATE TABLE APP_CHECKIN_RESUMEN (
    AREA VARCHAR2(12 CHAR) NOT NULL, SEMANA DATE NOT NULL,
    TOTAL NUMBER NOT NULL, COMPLETADAS NUMBER NOT NULL, PENDIENTES NUMBER NOT NULL,
    CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CHECKIN_RESUMEN PRIMARY KEY(AREA,SEMANA),
    CONSTRAINT CK_CHECKIN_RES_AREA CHECK(AREA IN ('COCINA','SALON','BARRA','COOPERATIVA')),
    CONSTRAINT CK_CHECKIN_RES_TOT CHECK(TOTAL=COMPLETADAS+PENDIENTES AND COMPLETADAS>=0 AND PENDIENTES>=0))~');
  ensure_table('APP_CHECKIN_OBSERVACION',q'~CREATE TABLE APP_CHECKIN_OBSERVACION (
    ID_OBSERVACION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AREA VARCHAR2(12 CHAR) NOT NULL, MENSAJE VARCHAR2(2000 CHAR) NOT NULL,
    ID_REMITENTE NUMBER NOT NULL, REMITENTE VARCHAR2(160 CHAR) NOT NULL,
    ID_DESTINATARIO NUMBER NOT NULL, DESTINATARIO VARCHAR2(160 CHAR) NOT NULL,
    CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_CHECKIN_OBS_AREA CHECK(AREA IN ('COCINA','SALON','BARRA','COOPERATIVA')))~');
  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME='IX_CHECKIN_REG_AREA_FECHA';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_CHECKIN_REG_AREA_FECHA ON APP_CHECKIN_REGISTRO(AREA,FECHA)'; END IF;
  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME='IX_CHECKIN_OBS_AREA';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_CHECKIN_OBS_AREA ON APP_CHECKIN_OBSERVACION(AREA,CREADO_EN)'; END IF;
END;
/
COMMIT;
SELECT INICIO FROM APP_CHECKIN_CONFIG WHERE ID=1;
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME LIKE 'APP_CHECKIN_%' ORDER BY TABLE_NAME;
