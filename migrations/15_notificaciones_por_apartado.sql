-- Preferencias por apartado para las notificaciones de MariGex.
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='APP_NOTIF_MODULO_PREF';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE APP_NOTIF_MODULO_PREF (
            ID_USUARIO NUMBER NOT NULL,
            MODULO VARCHAR2(40 CHAR) NOT NULL,
            HABILITADA CHAR(1) DEFAULT ''S'' NOT NULL,
            CONSTRAINT PK_NOTIF_MODULO_PREF PRIMARY KEY(ID_USUARIO, MODULO),
            CONSTRAINT FK_NOTIF_MOD_PREF_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES APP_USUARIO(ID_USUARIO) ON DELETE CASCADE,
            CONSTRAINT CK_NOTIF_MODULO_HABILITADA CHECK(HABILITADA IN (''S'',''N''))
        )';
    END IF;
END;
/
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME='APP_NOTIF_MODULO_PREF';
