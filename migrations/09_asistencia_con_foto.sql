-- Extiende la asistencia diaria con hora exacta y evidencia fotográfica de entrada/salida.
-- Ejecutar una vez en la base Oracle del sistema. Se puede volver a ejecutar.
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='ENTRADA_EN';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (ENTRADA_EN TIMESTAMP(6))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='SALIDA_EN';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (SALIDA_EN TIMESTAMP(6))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='FOTO_ENTRADA';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (FOTO_ENTRADA BLOB)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='TIPO_FOTO_ENTRADA';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (TIPO_FOTO_ENTRADA VARCHAR2(30 CHAR))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='FOTO_SALIDA';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (FOTO_SALIDA BLOB)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='TIPO_FOTO_SALIDA';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (TIPO_FOTO_SALIDA VARCHAR2(30 CHAR))'; END IF;
END;
/
