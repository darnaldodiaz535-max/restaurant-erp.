-- Solo amplía el esquema; conserva la frecuencia diaria de plantillas/registros existentes.
DECLARE
  n NUMBER;
  PROCEDURE add_column(t VARCHAR2,c VARCHAR2,ddl VARCHAR2) IS
    found NUMBER;
  BEGIN
    SELECT COUNT(*) INTO found FROM USER_TAB_COLUMNS WHERE TABLE_NAME=t AND COLUMN_NAME=c;
    IF found=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE '||t||' ADD ('||ddl||')'; END IF;
  END;
BEGIN
  add_column('APP_CHECKIN_PLANTILLA','FRECUENCIA',q'~FRECUENCIA VARCHAR2(10 CHAR) DEFAULT 'DIARIA' NOT NULL~');
  add_column('APP_CHECKIN_REGISTRO','FRECUENCIA',q'~FRECUENCIA VARCHAR2(10 CHAR) DEFAULT 'DIARIA' NOT NULL~');
  add_column('APP_CHECKIN_PLANTILLA','CODIGO_REFERENCIA','CODIGO_REFERENCIA VARCHAR2(40 CHAR)');
  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='CK_CHECKIN_PL_FREQ';
  IF n=0 THEN EXECUTE IMMEDIATE q'~ALTER TABLE APP_CHECKIN_PLANTILLA ADD CONSTRAINT CK_CHECKIN_PL_FREQ CHECK(FRECUENCIA IN ('DIARIA','SEMANAL'))~'; END IF;
  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='CK_CHECKIN_REG_FREQ';
  IF n=0 THEN EXECUTE IMMEDIATE q'~ALTER TABLE APP_CHECKIN_REGISTRO ADD CONSTRAINT CK_CHECKIN_REG_FREQ CHECK(FRECUENCIA IN ('DIARIA','SEMANAL'))~'; END IF;
  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='UQ_CHECKIN_PL_CODIGO';
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_CHECKIN_PLANTILLA ADD CONSTRAINT UQ_CHECKIN_PL_CODIGO UNIQUE(CODIGO_REFERENCIA)'; END IF;
END;
/
SELECT TABLE_NAME,COLUMN_NAME FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME IN ('APP_CHECKIN_PLANTILLA','APP_CHECKIN_REGISTRO') AND COLUMN_NAME='FRECUENCIA';
