-- Guarda la ubicación y precisión GPS validadas en cada marca de entrada/salida.
-- Ejecutar una vez en Oracle. Se puede volver a ejecutar sin duplicar columnas.
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='GPS_ENTRADA_LAT';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (GPS_ENTRADA_LAT NUMBER(10,7))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='GPS_ENTRADA_LON';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (GPS_ENTRADA_LON NUMBER(10,7))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='GPS_ENTRADA_PRECISION';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (GPS_ENTRADA_PRECISION NUMBER(8,2))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='GPS_ENTRADA_DISTANCIA';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (GPS_ENTRADA_DISTANCIA NUMBER(8,2))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='GPS_SALIDA_LAT';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (GPS_SALIDA_LAT NUMBER(10,7))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='GPS_SALIDA_LON';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (GPS_SALIDA_LON NUMBER(10,7))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='GPS_SALIDA_PRECISION';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (GPS_SALIDA_PRECISION NUMBER(8,2))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_ASISTENCIA' AND COLUMN_NAME='GPS_SALIDA_DISTANCIA';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA ADD (GPS_SALIDA_DISTANCIA NUMBER(8,2))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='APP_ASISTENCIA_QR';
    IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE APP_ASISTENCIA_QR (ID_CONFIG NUMBER(1) NOT NULL, LATITUD NUMBER(10,7) NOT NULL, LONGITUD NUMBER(10,7) NOT NULL, RADIO_METROS NUMBER(5) DEFAULT 100 NOT NULL, QR_ACTUAL VARCHAR2(64 CHAR), QR_VENCE NUMBER(13), QR_ANTERIOR VARCHAR2(64 CHAR), QR_ANTERIOR_VENCE NUMBER(13), CONSTRAINT PK_APP_ASISTENCIA_QR PRIMARY KEY (ID_CONFIG), CONSTRAINT CK_APP_ASISTENCIA_QR_ID CHECK (ID_CONFIG = 1), CONSTRAINT CK_APP_ASISTENCIA_QR_RADIO CHECK (RADIO_METROS BETWEEN 20 AND 1000))'; END IF;
END;
/
