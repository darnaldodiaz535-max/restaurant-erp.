-- Permite retirar la referencia del autor eliminado sin borrar planillas del resto del equipo.
-- No elimina trabajadores ni registros. Aplicar antes de publicar esta versión.
DECLARE
  PROCEDURE allow_null(t VARCHAR2,c VARCHAR2) IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS
      WHERE TABLE_NAME=t AND COLUMN_NAME=c AND NULLABLE='N';
    IF n>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE '||t||' MODIFY ('||c||' NULL)'; END IF;
  END;
BEGIN
  allow_null('APP_ASISTENCIA_PLANILLA','CREADO_POR');
  allow_null('APP_HORARIO_IMAGEN','CREADO_POR');
  allow_null('APP_FERIADO_USO','REGISTRADO_POR');
END;
/
SELECT TABLE_NAME,COLUMN_NAME,NULLABLE FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME='APP_ASISTENCIA_PLANILLA' AND COLUMN_NAME='CREADO_POR')
 OR (TABLE_NAME='APP_HORARIO_IMAGEN' AND COLUMN_NAME='CREADO_POR')
 OR (TABLE_NAME='APP_FERIADO_USO' AND COLUMN_NAME='REGISTRADO_POR');
