-- Reportes diarios (retención de 15 días), inquietudes con destinatario
-- jerárquico y evaluación mensual de jefaturas.
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'APP_REPORTE_DIARIO';
    IF n = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE APP_REPORTE_DIARIO (
                ID_REPORTE_DIARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
                AUTOR_USUARIO NUMBER NOT NULL,
                AREA VARCHAR2(20 CHAR) NOT NULL,
                FECHA_REPORTE DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
                TITULO VARCHAR2(160 CHAR) NOT NULL,
                DETALLE VARCHAR2(4000 CHAR) NOT NULL,
                CREADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT PK_APP_REPORTE_DIARIO PRIMARY KEY (ID_REPORTE_DIARIO),
                CONSTRAINT FK_REP_DIARIO_AUTOR FOREIGN KEY (AUTOR_USUARIO)
                    REFERENCES APP_USUARIO (ID_USUARIO),
                CONSTRAINT CK_REP_DIARIO_AREA CHECK (AREA IN ('SALON','COCINA','BARRA'))
            )
        ]';
    END IF;

    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'APP_COMUNICACION';
    IF n = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE APP_COMUNICACION (
                ID_COMUNICACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
                AUTOR_USUARIO NUMBER NOT NULL,
                DESTINATARIO_USUARIO NUMBER NOT NULL,
                AREA VARCHAR2(20 CHAR) NOT NULL,
                CATEGORIA VARCHAR2(30 CHAR) NOT NULL,
                ASUNTO VARCHAR2(160 CHAR) NOT NULL,
                MENSAJE VARCHAR2(3000 CHAR) NOT NULL,
                ESTADO VARCHAR2(20 CHAR) DEFAULT 'NUEVA' NOT NULL,
                CREADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                ACTUALIZADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT PK_APP_COMUNICACION PRIMARY KEY (ID_COMUNICACION),
                CONSTRAINT FK_COMUNICACION_AUTOR FOREIGN KEY (AUTOR_USUARIO)
                    REFERENCES APP_USUARIO (ID_USUARIO),
                CONSTRAINT FK_COMUNICACION_DEST FOREIGN KEY (DESTINATARIO_USUARIO)
                    REFERENCES APP_USUARIO (ID_USUARIO),
                CONSTRAINT CK_COMUNICACION_AREA CHECK (AREA IN ('SALON','COCINA','BARRA','COPERIA','GENERAL')),
                CONSTRAINT CK_COMUNICACION_TIPO CHECK (CATEGORIA IN ('INQUIETUD','QUEJA','SUGERENCIA','SITUACION')),
                CONSTRAINT CK_COMUNICACION_ESTADO CHECK (ESTADO IN ('NUEVA','EN_REVISION','RESPONDIDA','CERRADA'))
            )
        ]';
    END IF;

    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'APP_EVAL_JEFATURA';
    IF n = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE APP_EVAL_JEFATURA (
                ID_EVALUACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
                EVALUADOR_USUARIO NUMBER NOT NULL,
                EVALUADO_USUARIO NUMBER NOT NULL,
                AREA VARCHAR2(20 CHAR) NOT NULL,
                PERIODO VARCHAR2(7 CHAR) NOT NULL,
                PUNTAJE NUMBER(1) NOT NULL,
                COMENTARIO VARCHAR2(1000 CHAR),
                CREADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT PK_APP_EVAL_JEFATURA PRIMARY KEY (ID_EVALUACION),
                CONSTRAINT FK_EVAL_JEF_EVALUADOR FOREIGN KEY (EVALUADOR_USUARIO)
                    REFERENCES APP_USUARIO (ID_USUARIO),
                CONSTRAINT FK_EVAL_JEF_EVALUADO FOREIGN KEY (EVALUADO_USUARIO)
                    REFERENCES APP_USUARIO (ID_USUARIO),
                CONSTRAINT CK_EVAL_JEF_AREA CHECK (AREA IN ('SALON','COCINA','BARRA','COPERIA')),
                CONSTRAINT CK_EVAL_JEF_PUNTAJE CHECK (PUNTAJE BETWEEN 1 AND 5),
                CONSTRAINT UQ_EVAL_JEF_MES UNIQUE (EVALUADOR_USUARIO, AREA, PERIODO)
            )
        ]';
    END IF;

    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'APP_NOTIF_MODULO_PREF';
    IF n > 0 THEN
        EXECUTE IMMEDIATE q'[
        UPDATE APP_NOTIF_MODULO_PREF old_pref
           SET MODULO = 'Comunicación del equipo'
         WHERE MODULO = 'Incidencias'
           AND NOT EXISTS (
               SELECT 1 FROM APP_NOTIF_MODULO_PREF new_pref
                WHERE new_pref.ID_USUARIO = old_pref.ID_USUARIO
                  AND new_pref.MODULO = 'Comunicación del equipo'
           )]';
        EXECUTE IMMEDIATE q'[DELETE FROM APP_NOTIF_MODULO_PREF WHERE MODULO = 'Incidencias']';
    END IF;
END;
/

DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'IX_REP_DIARIO_FECHA';
    IF n = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_REP_DIARIO_FECHA ON APP_REPORTE_DIARIO (CREADO_EN)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'IX_COMUNICACION_DEST';
    IF n = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_COMUNICACION_DEST ON APP_COMUNICACION (DESTINATARIO_USUARIO, ESTADO, CREADO_EN)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'IX_COMUNICACION_AUTOR';
    IF n = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_COMUNICACION_AUTOR ON APP_COMUNICACION (AUTOR_USUARIO, CREADO_EN)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'IX_EVAL_JEF_AREA';
    IF n = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_EVAL_JEF_AREA ON APP_EVAL_JEFATURA (AREA, PERIODO, EVALUADO_USUARIO)'; END IF;
END;
/

SELECT TABLE_NAME FROM USER_TABLES
WHERE TABLE_NAME IN ('APP_REPORTE_DIARIO','APP_COMUNICACION','APP_EVAL_JEFATURA');
