-- Guarda la rotación de asistencia de Cocina, Salón y Barra en ciclos de dos semanas.
-- La planilla se carga desde Asistencia y cada versión queda vigente por dos meses.
-- Ejecutar una vez en la base Oracle del sistema. Se puede volver a ejecutar.
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='APP_ASISTENCIA_PLANILLA';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE APP_ASISTENCIA_PLANILLA (
            ID_PLANILLA NUMBER GENERATED BY DEFAULT AS IDENTITY,
            AREA VARCHAR2(10 CHAR) NOT NULL,
            VIGENTE_DESDE DATE NOT NULL,
            VIGENTE_HASTA DATE NOT NULL,
            CREADO_POR NUMBER NOT NULL,
            CREADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_APP_ASIS_PLAN PRIMARY KEY (ID_PLANILLA),
            CONSTRAINT CK_ASIS_PLAN_AREA CHECK (AREA IN (''COCINA'',''SALON'',''BARRA'')),
            CONSTRAINT CK_ASIS_PLAN_FECHAS CHECK (VIGENTE_HASTA>=VIGENTE_DESDE),
            CONSTRAINT UQ_ASIS_PLAN_AREA_F UNIQUE (AREA,VIGENTE_DESDE),
            CONSTRAINT FK_ASIS_PLAN_USER FOREIGN KEY (CREADO_POR) REFERENCES APP_USUARIO(ID_USUARIO)
        )';
    END IF;

    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='APP_ASISTENCIA_HORARIO';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE APP_ASISTENCIA_HORARIO (
            ID_HORARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
            ID_PLANILLA NUMBER NOT NULL,
            EMPLEADO_ID NUMBER NOT NULL,
            RUT_SNAPSHOT VARCHAR2(20 CHAR) NOT NULL,
            NOMBRE_SNAPSHOT VARCHAR2(160 CHAR) NOT NULL,
            SEMANA_CICLO NUMBER(1) NOT NULL,
            DIA_SEMANA NUMBER(1) NOT NULL,
            HORA_INICIO VARCHAR2(5 CHAR),
            HORA_FIN VARCHAR2(5 CHAR),
            ESTADO_DIA VARCHAR2(8 CHAR) NOT NULL,
            HORAS_PROGRAMADAS NUMBER(4,2) DEFAULT 0 NOT NULL,
            CREADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_ASIS_HORARIO PRIMARY KEY (ID_HORARIO),
            CONSTRAINT FK_ASIS_HOR_PLAN FOREIGN KEY (ID_PLANILLA) REFERENCES APP_ASISTENCIA_PLANILLA(ID_PLANILLA) ON DELETE CASCADE,
            CONSTRAINT FK_ASIS_HOR_EMP FOREIGN KEY (EMPLEADO_ID) REFERENCES APP_EMPLEADO(ID_EMPLEADO),
            CONSTRAINT UQ_ASIS_HOR_ROW UNIQUE (ID_PLANILLA,EMPLEADO_ID,SEMANA_CICLO,DIA_SEMANA),
            CONSTRAINT CK_ASIS_HOR_SEM CHECK (SEMANA_CICLO IN (1,2)),
            CONSTRAINT CK_ASIS_HOR_DIA CHECK (DIA_SEMANA BETWEEN 1 AND 7),
            CONSTRAINT CK_ASIS_HOR_EST CHECK (ESTADO_DIA IN (''TRABAJA'',''LIBRE'')),
            CONSTRAINT CK_ASIS_HOR_HRS CHECK (HORAS_PROGRAMADAS BETWEEN 0 AND 24),
            CONSTRAINT CK_ASIS_HOR_TURNO CHECK ((ESTADO_DIA=''LIBRE'' AND HORA_INICIO IS NULL AND HORA_FIN IS NULL AND HORAS_PROGRAMADAS=0) OR (ESTADO_DIA=''TRABAJA'' AND HORA_INICIO IS NOT NULL AND HORA_FIN IS NOT NULL AND HORAS_PROGRAMADAS>0))
        )';
    END IF;
END;
/
