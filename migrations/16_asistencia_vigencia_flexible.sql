-- Permite importar calendarios reales con una vigencia elegida de hasta 366 días.
-- Ejecutar una vez en Oracle antes de confirmar horarios de más de 62 días.
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
      WHERE TABLE_NAME='APP_ASISTENCIA_HORARIO' AND CONSTRAINT_NAME='CK_ASIS_HOR_SEM';
    IF n > 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_HORARIO DROP CONSTRAINT CK_ASIS_HOR_SEM'; END IF;
    EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_HORARIO ADD CONSTRAINT CK_ASIS_HOR_SEM CHECK (SEMANA_CICLO BETWEEN 1 AND 366)';

    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
      WHERE TABLE_NAME='APP_ASISTENCIA_PLANILLA' AND CONSTRAINT_NAME='CK_ASIS_PLAN_CICLO_DIAS';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE APP_ASISTENCIA_PLANILLA ADD CONSTRAINT CK_ASIS_PLAN_CICLO_DIAS CHECK (CICLO_DIAS BETWEEN 1 AND 366)';
    END IF;
END;
/
