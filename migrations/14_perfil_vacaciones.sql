-- Registra el uso del feriado legal y conserva la fecha de creación del acceso.
-- Ejecutar conectado al esquema de MariGex. Se puede volver a ejecutar.
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_USUARIO' AND COLUMN_NAME='CREADO_EN';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE APP_USUARIO ADD (CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL)';
    ELSE
        SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_USUARIO' AND COLUMN_NAME='CREADO_EN' AND NULLABLE='Y';
        IF n>0 THEN
            EXECUTE IMMEDIATE 'UPDATE APP_USUARIO SET CREADO_EN=SYSTIMESTAMP WHERE CREADO_EN IS NULL';
            EXECUTE IMMEDIATE 'ALTER TABLE APP_USUARIO MODIFY (CREADO_EN DEFAULT SYSTIMESTAMP NOT NULL)';
        END IF;
    END IF;
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='APP_FERIADO_USO';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE APP_FERIADO_USO (
            ID_USO NUMBER GENERATED BY DEFAULT AS IDENTITY,
            ID_EMPLEADO NUMBER NOT NULL,
            FECHA_USO DATE NOT NULL,
            DIAS NUMBER(5,2) NOT NULL,
            OBSERVACION VARCHAR2(300 CHAR),
            REGISTRADO_POR NUMBER NOT NULL,
            CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_APP_FERIADO_USO PRIMARY KEY(ID_USO),
            CONSTRAINT CK_FERIADO_USO_DIAS CHECK(DIAS>0 AND DIAS<=30)
        )';
    END IF;
END;
/
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME='APP_FERIADO_USO';
SELECT COLUMN_NAME, DATA_DEFAULT, NULLABLE FROM USER_TAB_COLUMNS WHERE TABLE_NAME='APP_USUARIO' AND COLUMN_NAME='CREADO_EN';
