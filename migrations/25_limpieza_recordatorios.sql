-- Ejecutar antes de publicar la versión Limpieza profunda semanal.
-- Crea el registro de avisos únicos de los lunes y conserva las preferencias existentes.
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='APP_CHECKIN_RECORDATORIO';
  IF n=0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE APP_CHECKIN_RECORDATORIO (
      ID_USUARIO NUMBER NOT NULL,
      SEMANA DATE NOT NULL,
      CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_CHECKIN_RECORDATORIO PRIMARY KEY(ID_USUARIO,SEMANA),
      CONSTRAINT FK_CHECKIN_RECORD_USER FOREIGN KEY(ID_USUARIO) REFERENCES APP_USUARIO(ID_USUARIO) ON DELETE CASCADE
    )~';
  END IF;
  -- If a new-name preference already exists, preserve that explicit choice.
  MERGE INTO APP_NOTIF_MODULO_PREF P
  USING (SELECT ID_USUARIO,HABILITADA FROM APP_NOTIF_MODULO_PREF WHERE MODULO='Check-in Diario') S
  ON(P.ID_USUARIO=S.ID_USUARIO AND P.MODULO='Limpieza profunda semanal')
  WHEN NOT MATCHED THEN INSERT(ID_USUARIO,MODULO,HABILITADA)
    VALUES(S.ID_USUARIO,'Limpieza profunda semanal',S.HABILITADA);
  DELETE FROM APP_NOTIF_MODULO_PREF WHERE MODULO='Check-in Diario';
  UPDATE APP_NOTIFICACION SET MODULO='Limpieza profunda semanal' WHERE MODULO='Check-in Diario';
END;
/
COMMIT;
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME='APP_CHECKIN_RECORDATORIO';
