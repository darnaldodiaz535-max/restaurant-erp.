-- Check-in Diario: migracion aditiva, reanudable y compatible con Oracle Database Actions.
-- Ejecutar como propietario del esquema APP_. No modifica ni elimina datos existentes.
-- Esta version corresponde al esquema actual, que aun no tiene soporte multiempresa.

DECLARE
    PROCEDURE require_table(p_name VARCHAR2) IS
        n NUMBER;
    BEGIN
        SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME=UPPER(p_name);
        IF n=0 THEN
            RAISE_APPLICATION_ERROR(-20001,'Falta la tabla requerida '||UPPER(p_name)||'. No se continuo.');
        END IF;
    END;

    PROCEDURE require_columns(p_table VARCHAR2,p_columns VARCHAR2) IS
        n NUMBER;
        total NUMBER;
        col VARCHAR2(128);
    BEGIN
        total:=REGEXP_COUNT(p_columns,',')+1;
        FOR i IN 1..total LOOP
            col:=UPPER(TRIM(REGEXP_SUBSTR(p_columns,'[^,]+',1,i)));
            SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS
             WHERE TABLE_NAME=UPPER(p_table) AND COLUMN_NAME=col;
            IF n=0 THEN
                RAISE_APPLICATION_ERROR(-20002,'Falta la columna '||UPPER(p_table)||'.'||col||'.');
            END IF;
        END LOOP;
    END;

    PROCEDURE ensure_table(p_name VARCHAR2,p_ddl VARCHAR2) IS
        n NUMBER;
    BEGIN
        SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME=UPPER(p_name);
        IF n=0 THEN EXECUTE IMMEDIATE p_ddl; END IF;
    END;

    PROCEDURE ensure_index(p_name VARCHAR2,p_ddl VARCHAR2) IS
        n NUMBER;
    BEGIN
        SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME=UPPER(p_name);
        IF n=0 THEN EXECUTE IMMEDIATE p_ddl; END IF;
    END;
BEGIN
    -- Validar primero el esquema existente que usa el modulo.
    require_table('APP_EMPLEADO');
    require_table('APP_USUARIO');
    require_table('APP_TURNO');
    require_columns('APP_EMPLEADO','ID_EMPLEADO,NOMBRE,AREA,ESTADO');
    require_columns('APP_USUARIO','ID_USUARIO,ID_EMPLEADO,ROL,ACTIVO');
    require_columns('APP_TURNO','EMPLEADO_ID,FECHA,AREA');

    ensure_table('APP_CHECKIN_PLANTILLA',q'~
        CREATE TABLE APP_CHECKIN_PLANTILLA (
            ID_PLANTILLA NUMBER GENERATED BY DEFAULT AS IDENTITY,
            AREA VARCHAR2(12 CHAR) NOT NULL,
            TAREA VARCHAR2(250 CHAR) NOT NULL,
            METODO_COMPLETADO VARCHAR2(10 CHAR) DEFAULT 'SIMPLE' NOT NULL,
            VIGENTE_DESDE DATE NOT NULL,
            VIGENTE_HASTA DATE,
            POSICION NUMBER(5) DEFAULT 0 NOT NULL,
            ACTIVA CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
            CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_CHECKIN_PLANTILLA PRIMARY KEY(ID_PLANTILLA),
            CONSTRAINT CK_CHECKIN_PL_AREA CHECK(AREA IN ('SALON','COPERIA','COCINA','BARRA')),
            CONSTRAINT CK_CHECKIN_PL_MET CHECK(METODO_COMPLETADO IN ('SIMPLE','FOTO')),
            CONSTRAINT CK_CHECKIN_PL_ACT CHECK(ACTIVA IN ('S','N'))
        )~');
    require_columns('APP_CHECKIN_PLANTILLA',
        'ID_PLANTILLA,AREA,TAREA,METODO_COMPLETADO,VIGENTE_DESDE,VIGENTE_HASTA,POSICION,ACTIVA,CREADO_EN');
    ensure_index('IX_CHECKIN_PL_AREA',
        'CREATE INDEX IX_CHECKIN_PL_AREA ON APP_CHECKIN_PLANTILLA(AREA,ACTIVA,POSICION)');

    ensure_table('APP_CHECKIN_DIA',q'~
        CREATE TABLE APP_CHECKIN_DIA (
            ID_CHECKIN_DIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
            FECHA_OPERATIVA DATE NOT NULL,
            ID_EMPLEADO NUMBER,
            ID_EMPLEADO_CLAVE NUMBER NOT NULL,
            NOMBRE_EMPLEADO VARCHAR2(160 CHAR) NOT NULL,
            AREA VARCHAR2(12 CHAR) NOT NULL,
            ESTADO_DIA VARCHAR2(10 CHAR) DEFAULT 'TRABAJADO' NOT NULL,
            CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_CHECKIN_DIA PRIMARY KEY(ID_CHECKIN_DIA),
            CONSTRAINT FK_CHECKIN_DIA_PERSONA FOREIGN KEY(ID_EMPLEADO)
                REFERENCES APP_EMPLEADO(ID_EMPLEADO) ON DELETE SET NULL,
            CONSTRAINT CK_CHECKIN_DIA_AREA CHECK(AREA IN ('SALON','COPERIA','COCINA','BARRA')),
            CONSTRAINT CK_CHECKIN_DIA_EST CHECK(ESTADO_DIA IN ('TRABAJADO','LIBRE')),
            CONSTRAINT UQ_CHECKIN_DIA_EMP UNIQUE(FECHA_OPERATIVA,ID_EMPLEADO_CLAVE)
        )~');
    require_columns('APP_CHECKIN_DIA',
        'ID_CHECKIN_DIA,FECHA_OPERATIVA,ID_EMPLEADO,ID_EMPLEADO_CLAVE,NOMBRE_EMPLEADO,AREA,ESTADO_DIA,CREADO_EN');
    ensure_index('IX_CHECKIN_DIA_EMP_FECHA',
        'CREATE INDEX IX_CHECKIN_DIA_EMP_FECHA ON APP_CHECKIN_DIA(ID_EMPLEADO_CLAVE,FECHA_OPERATIVA)');
    ensure_index('IX_CHECKIN_DIA_AREA_FECHA',
        'CREATE INDEX IX_CHECKIN_DIA_AREA_FECHA ON APP_CHECKIN_DIA(AREA,FECHA_OPERATIVA)');

    ensure_table('APP_CHECKIN_TAREA',q'~
        CREATE TABLE APP_CHECKIN_TAREA (
            ID_CHECKIN_TAREA NUMBER GENERATED BY DEFAULT AS IDENTITY,
            ID_CHECKIN_DIA NUMBER NOT NULL,
            ID_PLANTILLA NUMBER,
            TAREA_SNAPSHOT VARCHAR2(250 CHAR) NOT NULL,
            METODO_COMPLETADO VARCHAR2(10 CHAR) NOT NULL,
            ESTADO VARCHAR2(12 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
            REALIZADA_EN TIMESTAMP(6),
            CONSTRAINT PK_CHECKIN_TAREA PRIMARY KEY(ID_CHECKIN_TAREA),
            CONSTRAINT FK_CHECKIN_TAREA_DIA FOREIGN KEY(ID_CHECKIN_DIA)
                REFERENCES APP_CHECKIN_DIA(ID_CHECKIN_DIA),
            CONSTRAINT FK_CHECKIN_TAREA_PL FOREIGN KEY(ID_PLANTILLA)
                REFERENCES APP_CHECKIN_PLANTILLA(ID_PLANTILLA) ON DELETE SET NULL,
            CONSTRAINT CK_CHECKIN_TAREA_MET CHECK(METODO_COMPLETADO IN ('SIMPLE','FOTO')),
            CONSTRAINT CK_CHECKIN_TAREA_EST CHECK(ESTADO IN ('PENDIENTE','REALIZADA')),
            CONSTRAINT UQ_CHECKIN_TAREA_DIA UNIQUE(ID_CHECKIN_DIA,ID_PLANTILLA)
        )~');
    require_columns('APP_CHECKIN_TAREA',
        'ID_CHECKIN_TAREA,ID_CHECKIN_DIA,ID_PLANTILLA,TAREA_SNAPSHOT,METODO_COMPLETADO,ESTADO,REALIZADA_EN');
    ensure_index('IX_CHECKIN_TAREA_DIA',
        'CREATE INDEX IX_CHECKIN_TAREA_DIA ON APP_CHECKIN_TAREA(ID_CHECKIN_DIA,ESTADO)');

    ensure_table('APP_CHECKIN_FOTO',q'~
        CREATE TABLE APP_CHECKIN_FOTO (
            ID_FOTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
            ID_CHECKIN_TAREA NUMBER NOT NULL,
            NOMBRE_ARCHIVO VARCHAR2(255 CHAR) NOT NULL,
            TIPO_CONTENIDO VARCHAR2(100 CHAR) NOT NULL,
            FOTO BLOB,
            CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            ELIMINADA_EN TIMESTAMP(6),
            CONSTRAINT PK_CHECKIN_FOTO PRIMARY KEY(ID_FOTO),
            CONSTRAINT FK_CHECKIN_FOTO_TAREA FOREIGN KEY(ID_CHECKIN_TAREA)
                REFERENCES APP_CHECKIN_TAREA(ID_CHECKIN_TAREA) ON DELETE CASCADE,
            CONSTRAINT CK_CHECKIN_FOTO_TIPO CHECK(TIPO_CONTENIDO IN ('image/jpeg','image/png','image/webp')),
            CONSTRAINT UQ_CHECKIN_FOTO_TASK UNIQUE(ID_CHECKIN_TAREA)
        )~');
    require_columns('APP_CHECKIN_FOTO',
        'ID_FOTO,ID_CHECKIN_TAREA,NOMBRE_ARCHIVO,TIPO_CONTENIDO,FOTO,CREADO_EN,ELIMINADA_EN');

    ensure_table('APP_CHECKIN_ENVIO_SEMANAL',q'~
        CREATE TABLE APP_CHECKIN_ENVIO_SEMANAL (
            ID_ENVIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
            ID_USUARIO NUMBER,
            DESTINATARIO_CLAVE VARCHAR2(80 CHAR) NOT NULL,
            DESTINATARIO_NOMBRE VARCHAR2(160 CHAR) NOT NULL,
            SEMANA_INICIO DATE NOT NULL,
            TIPO_REPORTE VARCHAR2(10 CHAR) NOT NULL,
            DETALLE CLOB,
            ESTADO_ENVIO VARCHAR2(12 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
            CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            ENVIADO_EN TIMESTAMP(6),
            CONSTRAINT PK_CHECKIN_ENVIO PRIMARY KEY(ID_ENVIO),
            CONSTRAINT CK_CHECKIN_ENVIO_TIPO CHECK(TIPO_REPORTE IN ('PERSONAL','ADMIN')),
            CONSTRAINT CK_CHECKIN_ENVIO_EST CHECK(ESTADO_ENVIO IN ('PENDIENTE','ENVIADO')),
            CONSTRAINT UQ_CHECKIN_ENVIO_UNICO UNIQUE(SEMANA_INICIO,TIPO_REPORTE,DESTINATARIO_CLAVE)
        )~');
    require_columns('APP_CHECKIN_ENVIO_SEMANAL',
        'ID_ENVIO,ID_USUARIO,DESTINATARIO_CLAVE,DESTINATARIO_NOMBRE,SEMANA_INICIO,TIPO_REPORTE,DETALLE,ESTADO_ENVIO,CREADO_EN,ENVIADO_EN');
    ensure_index('IX_CHECKIN_ENVIO_SEMANA',
        'CREATE INDEX IX_CHECKIN_ENVIO_SEMANA ON APP_CHECKIN_ENVIO_SEMANAL(SEMANA_INICIO,TIPO_REPORTE)');

    ensure_table('APP_CHECKIN_AVISO_DIA',q'~
        CREATE TABLE APP_CHECKIN_AVISO_DIA (
            ID_AVISO NUMBER GENERATED BY DEFAULT AS IDENTITY,
            FECHA_OPERATIVA DATE NOT NULL,
            ID_EMPLEADO_CLAVE NUMBER NOT NULL,
            CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_CHECKIN_AVISO PRIMARY KEY(ID_AVISO),
            CONSTRAINT UQ_CHECKIN_AVISO_DIA UNIQUE(FECHA_OPERATIVA,ID_EMPLEADO_CLAVE)
        )~');
    require_columns('APP_CHECKIN_AVISO_DIA',
        'ID_AVISO,FECHA_OPERATIVA,ID_EMPLEADO_CLAVE,CREADO_EN');

    DBMS_OUTPUT.PUT_LINE('Migracion Check-in Diario completada o ya estaba aplicada.');
END;
