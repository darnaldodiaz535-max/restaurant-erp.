-- Permite que una persona evalúe por separado a cada jefatura una vez al mes.
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'APP_EVAL_JEFATURA'
       AND CONSTRAINT_NAME = 'UQ_EVAL_JEF_MES';
    IF n > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE APP_EVAL_JEFATURA DROP CONSTRAINT UQ_EVAL_JEF_MES';
    END IF;

    SELECT COUNT(*) INTO n
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'APP_EVAL_JEFATURA'
       AND CONSTRAINT_NAME = 'UQ_EVAL_JEF_DEST_MES';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE APP_EVAL_JEFATURA ADD CONSTRAINT UQ_EVAL_JEF_DEST_MES UNIQUE (EVALUADOR_USUARIO, EVALUADO_USUARIO, PERIODO)';
    END IF;
END;
/
