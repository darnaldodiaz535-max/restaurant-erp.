CREATE TABLE APP_USUARIO (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_EMPLEADO NUMBER NOT NULL,
    USUARIO VARCHAR2(60 CHAR) NOT NULL,
    CLAVE_HASH VARCHAR2(300 CHAR) NOT NULL,
    ROL VARCHAR2(20 CHAR) DEFAULT 'EMPLEADO' NOT NULL,
    ACTIVO CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_APP_USUARIO_EMPLEADO UNIQUE (ID_EMPLEADO),
    CONSTRAINT UQ_APP_USUARIO_USUARIO UNIQUE (USUARIO),
    CONSTRAINT FK_APP_USUARIO_EMPLEADO FOREIGN KEY (ID_EMPLEADO)
        REFERENCES APP_EMPLEADO (ID_EMPLEADO) ON DELETE CASCADE,
    CONSTRAINT CK_APP_USUARIO_ROL CHECK (ROL IN ('ADMIN', 'EMPRESA', 'JEFE_SALON', 'JEFE_COCINA', 'TRABAJADOR', 'EMPLEADO')),
    CONSTRAINT CK_APP_USUARIO_ACTIVO CHECK (ACTIVO IN ('S', 'N'))
);
