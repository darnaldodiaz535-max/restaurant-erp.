-- Amplía los roles disponibles y agrega una tabla Oracle para las fotos de tareas.
ALTER TABLE APP_USUARIO DROP CONSTRAINT CK_APP_USUARIO_ROL;
ALTER TABLE APP_USUARIO ADD CONSTRAINT CK_APP_USUARIO_ROL
    CHECK (ROL IN ('ADMIN', 'EMPRESA', 'JEFE_SALON', 'JEFE_COCINA', 'TRABAJADOR', 'EMPLEADO'));

UPDATE APP_USUARIO SET ROL = 'EMPRESA' WHERE ROL = 'ADMIN';
UPDATE APP_USUARIO SET ROL = 'TRABAJADOR' WHERE ROL = 'EMPLEADO';

CREATE TABLE APP_EVIDENCIA_TAREA (
    ID_EVIDENCIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_TAREA NUMBER NOT NULL,
    ID_EMPLEADO NUMBER NOT NULL,
    NOMBRE_ARCHIVO VARCHAR2(255 CHAR) NOT NULL,
    TIPO_CONTENIDO VARCHAR2(100 CHAR) NOT NULL,
    FOTO BLOB NOT NULL,
    ESTADO VARCHAR2(20 CHAR) DEFAULT 'ENVIADA' NOT NULL,
    CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_EVIDENCIA_TAREA PRIMARY KEY (ID_EVIDENCIA),
    CONSTRAINT FK_EVIDENCIA_TAREA FOREIGN KEY (ID_TAREA) REFERENCES APP_TAREA_DIARIA (ID_TAREA),
    CONSTRAINT FK_EVIDENCIA_EMPLEADO FOREIGN KEY (ID_EMPLEADO) REFERENCES APP_EMPLEADO (ID_EMPLEADO),
    CONSTRAINT CK_EVIDENCIA_ESTADO CHECK (ESTADO IN ('ENVIADA', 'REVISADA'))
);

COMMIT;
