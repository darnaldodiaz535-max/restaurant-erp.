CREATE TABLE APP_ACTIVIDAD (
    ID_ACTIVIDAD NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USUARIO VARCHAR2(60 CHAR) NOT NULL,
    ACCION VARCHAR2(20 CHAR) NOT NULL,
    MODULO VARCHAR2(60 CHAR) NOT NULL,
    DETALLE VARCHAR2(500 CHAR) NOT NULL,
    CREADO_EN TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_ACTIVIDAD PRIMARY KEY (ID_ACTIVIDAD)
);
