-- No ejecutar APP_ESQUEMA.sql de nuevo. No cambia ni elimina tablas/datos existentes.
-- DDL Oracle confirma automáticamente. Las tablas nuevas permanecen si un paso posterior falla.
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
  n NUMBER;
BEGIN
  IF USER <> 'RESTAPI_HOY2609' THEN
    RAISE_APPLICATION_ERROR(-20001, 'Conéctate como RESTAPI_HOY2609 antes de ejecutar esta migración.');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='APP_NOTIFICACION';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE APP_NOTIFICACION (
      ID_NOTIFICACION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ID_USUARIO NUMBER NOT NULL,
      MODULO VARCHAR2(60 CHAR) NOT NULL,
      MENSAJE VARCHAR2(1000 CHAR) NOT NULL,
      LEIDA CHAR(1) DEFAULT ''N'' NOT NULL,
      CREADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT FK_NOTIF_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES APP_USUARIO(ID_USUARIO) ON DELETE CASCADE,
      CONSTRAINT CK_NOTIF_LEIDA CHECK(LEIDA IN (''S'',''N'')))';
  END IF;
  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME='IX_NOTIF_USUARIO';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_NOTIF_USUARIO ON APP_NOTIFICACION(ID_USUARIO,LEIDA,ID_NOTIFICACION)'; END IF;
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='APP_PROPUESTA_HORARIO';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE APP_PROPUESTA_HORARIO (
      ID_PROPUESTA VARCHAR2(36 CHAR) PRIMARY KEY,
      ID_USUARIO NUMBER NOT NULL,
      FECHA_INICIO DATE NOT NULL,
      CONTENIDO CLOB NOT NULL,
      ESTADO VARCHAR2(12 CHAR) DEFAULT ''BORRADOR'' NOT NULL,
      CREADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT FK_PROP_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES APP_USUARIO(ID_USUARIO) ON DELETE CASCADE,
      CONSTRAINT CK_PROP_ESTADO CHECK(ESTADO IN (''BORRADOR'',''PUBLICADO'')))';
  END IF;
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='APP_HORARIO_DESTINATARIO';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE APP_HORARIO_DESTINATARIO (
      ID_HORARIO NUMBER NOT NULL, ID_EMPLEADO NUMBER NOT NULL,
      CONSTRAINT PK_HORARIO_DEST PRIMARY KEY(ID_HORARIO,ID_EMPLEADO),
      CONSTRAINT FK_HDEST_HORARIO FOREIGN KEY(ID_HORARIO) REFERENCES APP_HORARIO_IMAGEN(ID_HORARIO) ON DELETE CASCADE,
      CONSTRAINT FK_HDEST_EMPLEADO FOREIGN KEY(ID_EMPLEADO) REFERENCES APP_EMPLEADO(ID_EMPLEADO) ON DELETE CASCADE)';
  END IF;
END;
/
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME IN ('APP_NOTIFICACION','APP_PROPUESTA_HORARIO','APP_HORARIO_DESTINATARIO');
