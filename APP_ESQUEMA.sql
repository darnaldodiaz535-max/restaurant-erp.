-- Esquema inicial del ERP de restaurante para una base Oracle cloud NUEVA.
-- Ejecutar UNA VEZ conectado con el usuario de esquema RESTAURANTE_APP.
-- Este script crea tablas vacías; no copia los registros de la base local.
-- No ejecutar este script sobre la base local que ya contiene tablas APP_.

CREATE TABLE APP_EMPLEADO (
    ID_EMPLEADO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE      VARCHAR2(160 CHAR) NOT NULL,
    CARGO       VARCHAR2(80 CHAR) NOT NULL,
    AREA        VARCHAR2(80 CHAR) NOT NULL,
    ESTADO      VARCHAR2(10 CHAR) DEFAULT 'ACTIVO' NOT NULL,
    CREADO_EN   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_EMPLEADO PRIMARY KEY (ID_EMPLEADO),
    CONSTRAINT CK_APP_EMP_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE APP_ASISTENCIA (
    ID_ASISTENCIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EMPLEADO_ID   NUMBER NOT NULL,
    FECHA         DATE NOT NULL,
    HORA_ENTRADA  VARCHAR2(5 CHAR) NOT NULL,
    HORA_SALIDA   VARCHAR2(5 CHAR),
    ESTADO        VARCHAR2(30 CHAR) DEFAULT 'PRESENTE' NOT NULL,
    CREADO_EN     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_ASISTENCIA PRIMARY KEY (ID_ASISTENCIA),
    CONSTRAINT FK_APP_ASIS_EMP FOREIGN KEY (EMPLEADO_ID)
        REFERENCES APP_EMPLEADO (ID_EMPLEADO)
);

CREATE TABLE APP_TURNO (
    ID_TURNO     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EMPLEADO_ID  NUMBER NOT NULL,
    FECHA        DATE NOT NULL,
    HORA_INICIO  VARCHAR2(5 CHAR) NOT NULL,
    HORA_TERMINO VARCHAR2(5 CHAR) NOT NULL,
    AREA         VARCHAR2(80 CHAR) NOT NULL,
    CREADO_EN    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_TURNO PRIMARY KEY (ID_TURNO),
    CONSTRAINT FK_APP_TURNO_EMP FOREIGN KEY (EMPLEADO_ID)
        REFERENCES APP_EMPLEADO (ID_EMPLEADO)
);

CREATE TABLE APP_TAREA_DIARIA (
    ID_TAREA      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TAREA         VARCHAR2(250 CHAR) NOT NULL,
    RESPONSABLE_ID NUMBER,
    FECHA         DATE NOT NULL,
    ESTADO        VARCHAR2(30 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    CREADO_EN     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_TAREA PRIMARY KEY (ID_TAREA),
    CONSTRAINT FK_APP_TAREA_EMP FOREIGN KEY (RESPONSABLE_ID)
        REFERENCES APP_EMPLEADO (ID_EMPLEADO) ON DELETE SET NULL
);

CREATE TABLE APP_INSUMO (
    ID_INSUMO    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE       VARCHAR2(160 CHAR) NOT NULL,
    CATEGORIA    VARCHAR2(80 CHAR) NOT NULL,
    STOCK_ACTUAL NUMBER(12,3) DEFAULT 0 NOT NULL,
    UNIDAD       VARCHAR2(30 CHAR) NOT NULL,
    GRUPO VARCHAR2(10 CHAR),
    STOCK_MINIMO NUMBER(12,3) DEFAULT 0 NOT NULL,
    CREADO_EN    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_INSUMO PRIMARY KEY (ID_INSUMO),
    CONSTRAINT CK_APP_INSUMO_STOCK CHECK (STOCK_ACTUAL >= 0 AND STOCK_MINIMO >= 0),
    CONSTRAINT CK_APP_INSUMO_GRUPO
    CHECK (GRUPO IN ('COCINA', 'BARRA'))
);

CREATE TABLE APP_COCINA (
    ID_COCINA     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PREPARACION   VARCHAR2(160 CHAR) NOT NULL,
    RESPONSABLE_ID NUMBER,
    HORA          VARCHAR2(5 CHAR) NOT NULL,
    ESTADO        VARCHAR2(30 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    CREADO_EN     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_COCINA PRIMARY KEY (ID_COCINA),
    CONSTRAINT FK_APP_COCINA_EMP FOREIGN KEY (RESPONSABLE_ID)
        REFERENCES APP_EMPLEADO (ID_EMPLEADO) ON DELETE SET NULL
);

CREATE TABLE APP_PRODUCCION (
    ID_PRODUCCION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PREPARACION   VARCHAR2(160 CHAR) NOT NULL,
    CANTIDAD      NUMBER(12,3) NOT NULL,
    UNIDAD        VARCHAR2(30 CHAR) NOT NULL,
    RESPONSABLE_ID NUMBER,
    FECHA         DATE NOT NULL,
    CREADO_EN     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_PRODUCCION PRIMARY KEY (ID_PRODUCCION),
    CONSTRAINT FK_APP_PROD_EMP FOREIGN KEY (RESPONSABLE_ID)
        REFERENCES APP_EMPLEADO (ID_EMPLEADO) ON DELETE SET NULL,
    CONSTRAINT CK_APP_PROD_CANT CHECK (CANTIDAD > 0)
);

CREATE TABLE APP_MISE_EN_PLACE (
    ID_MISE       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PREPARACION   VARCHAR2(160 CHAR) NOT NULL,
    CANTIDAD      NUMBER(12,3) NOT NULL,
    RESPONSABLE_ID NUMBER,
    HORA_LIMITE   VARCHAR2(5 CHAR) NOT NULL,
    ESTADO        VARCHAR2(30 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    CREADO_EN     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_MISE PRIMARY KEY (ID_MISE),
    CONSTRAINT FK_APP_MISE_EMP FOREIGN KEY (RESPONSABLE_ID)
        REFERENCES APP_EMPLEADO (ID_EMPLEADO) ON DELETE SET NULL,
    CONSTRAINT CK_APP_MISE_CANT CHECK (CANTIDAD > 0)
);

CREATE TABLE APP_RESERVA (
    ID_RESERVA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CLIENTE    VARCHAR2(160 CHAR) NOT NULL,
    FECHA      DATE NOT NULL,
    HORA       VARCHAR2(5 CHAR) NOT NULL,
    PERSONAS   NUMBER(4) NOT NULL,
    CONTACTO   VARCHAR2(80 CHAR) NOT NULL,
    ESTADO     VARCHAR2(30 CHAR) DEFAULT 'CONFIRMADA' NOT NULL,
    CREADO_EN  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_RESERVA PRIMARY KEY (ID_RESERVA),
    CONSTRAINT CK_APP_RES_PERSONAS CHECK (PERSONAS > 0)
);

CREATE TABLE APP_LIMPIEZA (
    ID_LIMPIEZA  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    AREA         VARCHAR2(80 CHAR) NOT NULL,
    TAREA        VARCHAR2(250 CHAR) NOT NULL,
    RESPONSABLE_ID NUMBER,
    FRECUENCIA   VARCHAR2(50 CHAR) NOT NULL,
    ESTADO       VARCHAR2(30 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    CREADO_EN    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_LIMPIEZA PRIMARY KEY (ID_LIMPIEZA),
    CONSTRAINT FK_APP_LIMP_EMP FOREIGN KEY (RESPONSABLE_ID)
        REFERENCES APP_EMPLEADO (ID_EMPLEADO) ON DELETE SET NULL
);

CREATE TABLE APP_INCIDENCIA (
    ID_INCIDENCIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TIPO          VARCHAR2(100 CHAR) NOT NULL,
    AREA          VARCHAR2(80 CHAR) NOT NULL,
    DESCRIPCION   VARCHAR2(1000 CHAR) NOT NULL,
    RESPONSABLE_ID NUMBER,
    ESTADO        VARCHAR2(30 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    CREADO_EN     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_INCIDENCIA PRIMARY KEY (ID_INCIDENCIA),
    CONSTRAINT FK_APP_INCI_EMP FOREIGN KEY (RESPONSABLE_ID)
        REFERENCES APP_EMPLEADO (ID_EMPLEADO) ON DELETE SET NULL
);

CREATE TABLE APP_COMPRA (
    ID_COMPRA  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PRODUCTO   VARCHAR2(160 CHAR) NOT NULL,
    CANTIDAD   NUMBER(12,3) NOT NULL,
    PROVEEDOR  VARCHAR2(160 CHAR) NOT NULL,
    FECHA      DATE NOT NULL,
    ESTADO     VARCHAR2(30 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    CREADO_EN  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_COMPRA PRIMARY KEY (ID_COMPRA),
    CONSTRAINT CK_APP_COMPRA_CANT CHECK (CANTIDAD > 0)
);

CREATE TABLE APP_MERMA (
    ID_MERMA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PRODUCTO VARCHAR2(160 CHAR) NOT NULL,
    CANTIDAD NUMBER(12,3) NOT NULL,
    UNIDAD   VARCHAR2(30 CHAR) NOT NULL,
    MOTIVO   VARCHAR2(500 CHAR) NOT NULL,
    FECHA    DATE NOT NULL,
    CREADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_MERMA PRIMARY KEY (ID_MERMA),
    CONSTRAINT CK_APP_MERMA_CANT CHECK (CANTIDAD > 0)
);

CREATE TABLE APP_CONTROL_SANITARIO (
    ID_CONTROL     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUNTO_CONTROL  VARCHAR2(160 CHAR) NOT NULL,
    TEMPERATURA_C  NUMBER(5,2) NOT NULL,
    FECHA_HORA     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    RESPONSABLE_ID NUMBER,
    ESTADO         VARCHAR2(30 CHAR) DEFAULT 'REGISTRADO' NOT NULL,
    CONSTRAINT PK_APP_CONTROL PRIMARY KEY (ID_CONTROL),
    CONSTRAINT FK_APP_CTRL_EMP FOREIGN KEY (RESPONSABLE_ID)
        REFERENCES APP_EMPLEADO (ID_EMPLEADO) ON DELETE SET NULL
);

CREATE TABLE APP_REPORTE (
    ID_REPORTE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE     VARCHAR2(160 CHAR) NOT NULL,
    PERIODO    VARCHAR2(80 CHAR) NOT NULL,
    FECHA      DATE DEFAULT SYSDATE NOT NULL,
    ESTADO     VARCHAR2(30 CHAR) DEFAULT 'DISPONIBLE' NOT NULL,
    CONSTRAINT PK_APP_REPORTE PRIMARY KEY (ID_REPORTE)
);

CREATE TABLE APP_CONFIGURACION (
    ID_CONFIGURACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    OPCION           VARCHAR2(100 CHAR) NOT NULL,
    VALOR            VARCHAR2(1000 CHAR),
    DESCRIPCION      VARCHAR2(500 CHAR),
    CONSTRAINT PK_APP_CONFIG PRIMARY KEY (ID_CONFIGURACION),
    CONSTRAINT UQ_APP_CONFIG_OPCION UNIQUE (OPCION)
);

-- Verifica las tablas creadas en el esquema de la aplicación.
SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME LIKE 'APP_%'
ORDER BY TABLE_NAME;
